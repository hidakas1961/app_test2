#include "common/common.hpp"
#include <nlohmann/json.hpp>

//=============================================================================
// 共通ライブラリ名前空間
//-----------------------------------------------------------------------------
namespace lib_common {
    //=========================================================================
    // 構成情報クラス
    //=========================================================================
    // 非公開構築子と解体子
    //-------------------------------------------------------------------------
    // コンストラクタ
    Config::Config(Node* pcParent) noexcept:
        // 基底クラスコンストラクタ
        Node(pcParent)
    {
        // 処理ブロック
        do {
            std::cout << std::format("-------------------------------------------------------------------------------\n");
            std::cout << std::format("構成情報クラス：コンストラクタ\n");
            std::cout << std::format("ノード名：{}\n", getName());
            std::cout << std::format("JSONパス：{}\n", getJsonPointer());
        } while (false);
    }

    //-------------------------------------------------------------------------
    // デストラクタ
    //-------------------------------------------------------------------------
    // デストラクタ
    Config::~Config() noexcept {
        // 処理ブロック
        do {
            // 関数情報出力
            std::cout << std::format("-------------------------------------------------------------------------------\n");
            std::cout << std::format("構成情報クラス：デストラクタ\n");
        } while (false);
    }

    //=========================================================================
    // 動的公開関数
    //-------------------------------------------------------------------------
    // JSONクラスインスタンス取得関数
    json& Config::getJson() noexcept {
        static json s_cJson; ///< JSONクラスインスタンス
        return s_cJson;
    }
}
