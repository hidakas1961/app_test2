#pragma once

//=============================================================================
// インクルードファイル
//-----------------------------------------------------------------------------
#include "common/common.h"
#include <string>

//=============================================================================
// 共通名前空間
//-----------------------------------------------------------------------------
namespace common {
    //=========================================================================
    /// ノードクラス
    ///
    /// ノードクラスです。
    ///
    /// @attention なし
    //-------------------------------------------------------------------------
    class Node {
        //=====================================================================
        // インライン公開構築子と解体子
        //---------------------------------------------------------------------
    public:
        //---------------------------------------------------------------------
        /// デフォルトコンストラクタ
        ///
        /// デフォルトコンストラクタです。
        ///
        /// @param     なし
        /// @return    なし
        /// @attention デフォルト定義のコンストラクタです。
        //---------------------------------------------------------------------
        inline Node() = default;

        //---------------------------------------------------------------------
        /// コンストラクタ
        ///
        /// コンストラクタです。
        ///
        /// @param[in] pcParent 親ノードクラスポインタ
        /// @return    なし
        /// @attention なし
        //---------------------------------------------------------------------
        inline explicit Node(Node* pcParent) noexcept: m_pcParent{pcParent} {}

        //---------------------------------------------------------------------
        /// デストラクタ
        ///
        /// デストラクタです。
        ///
        /// @param     なし
        /// @return    なし
        /// @attention デフォルト定義の仮想デストラクタです。
        //---------------------------------------------------------------------
        inline virtual ~Node() = default;

        //=====================================================================
        // 動的公開関数
        //---------------------------------------------------------------------
    public:
        //---------------------------------------------------------------------
        /// JSONパス文字列取得関数
        ///
        /// JSONパス文字列取得関数です。
        ///
        /// @param     なし
        /// @return    文字列クラス
        /// @attention なし
        //---------------------------------------------------------------------
        std::string const getJsonPath() const noexcept;

        //=====================================================================
        // インライン動的公開関数
        //---------------------------------------------------------------------
    public:
        //---------------------------------------------------------------------
        /// 親ノード取得関数
        ///
        /// 親ノード取得関数です。
        ///
        /// @param     なし
        /// @return    ノードクラスポインタ
        /// @attention なし
        //---------------------------------------------------------------------
        inline Node* getParent() const noexcept {return m_pcParent;}

        //=====================================================================
        // インライン公開仮想関数
        //---------------------------------------------------------------------
    public:
        //---------------------------------------------------------------------
        /// ノード名取得関数
        ///
        /// ノード名取得関数です。
        ///
        /// @param     なし
        /// @return    文字列クラス
        /// @attention なし
        //---------------------------------------------------------------------
        inline virtual std::string const getName() const noexcept {return "";}

        //---------------------------------------------------------------------
        /// 次ノード取得関数
        ///
        /// 次ノード取得関数です。
        ///
        /// @param     なし
        /// @return    ノードクラスポインタ
        /// @attention なし
        //---------------------------------------------------------------------
        inline virtual Node* getNext() const noexcept {return nullptr;}

        //=====================================================================
        // 動的非公開変数
        //---------------------------------------------------------------------
    private:
        Node* m_pcParent{}; ///< 親ノードクラスポインタ
    };
}
