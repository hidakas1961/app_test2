namespace common {
    //=========================================================================
    // ノードクラス
    //=========================================================================
    // 動的公開関数
    //-------------------------------------------------------------------------
    // JSONパス文字列取得関数
    std::string const Node::getJsonPointer() const noexcept {
        // 親ノードポインタ判別
        if (nullptr == m_pcParent) {
            // ノード名取得
            return "/"+getName();
        }
        
        // JSONパス文字列とノード名取得
        return m_pcParent->getJsonPointer()+"/"+getName();
    }
}
