namespace program {
    //=========================================================================
    /// プログラムクラス
    ///
    /// プログラムクラスです。
    ///
    /// @attention シングルトンクラスです。
    //-------------------------------------------------------------------------
    class Program final: public common::Node {
        //=====================================================================
        // 非公開削除関数
        //---------------------------------------------------------------------
    private:
        //---------------------------------------------------------------------
        /// コピーコンストラクタ
        ///
        /// コピーコンストラクタです。
        ///
        /// @param[in] インスタンス参照
        /// @return    なし
        /// @attention この関数を削除しました。
        //---------------------------------------------------------------------
        Program(Program const&) = delete;

        //---------------------------------------------------------------------
        /// インスタンスコピー代入演算子オーバーロード関数
        ///
        /// インスタンスコピー代入演算子オーバーロード関数です。
        ///
        /// @param[in] インスタンス参照
        /// @return    なし
        /// @attention この関数を削除しました。
        //---------------------------------------------------------------------
        Program& operator=(Program const&) = delete;

        //=====================================================================
        // 静的公開関数
        //---------------------------------------------------------------------
    public:
        //---------------------------------------------------------------------
        /// メイン関数
        ///
        /// メイン関数です。
        ///
        /// @param[in] hInstance インスタンスハンドル
        /// @return    実行結果
        /// @attention アプリケーション側で実装が必要です。
        //---------------------------------------------------------------------
        static int Main(HINSTANCE hInstance) noexcept;

        //=====================================================================
        // 非公開構築子と解体子
        //---------------------------------------------------------------------
    private:
        //---------------------------------------------------------------------
        /// コンストラクタ
        ///
        /// コンストラクタです。
        ///
        /// @param     なし
        /// @return    なし
        /// @attention なし
        //---------------------------------------------------------------------
        explicit Program() noexcept;

        //---------------------------------------------------------------------
        /// デストラクタ
        ///
        /// デストラクタです。
        ///
        /// @param     なし
        /// @return    なし
        /// @attention なし
        //---------------------------------------------------------------------
        virtual ~Program() noexcept;

        //=====================================================================
        // インライン静的公開関数
        //---------------------------------------------------------------------
    public:
        //---------------------------------------------------------------------
        /// インスタンス取得関数
        ///
        /// インスタンス取得関数です。
        ///
        /// @param     なし
        /// @return    プログラムクラスインスタンス参照
        /// @attention なし
        //---------------------------------------------------------------------
        inline static Program& getInstance() noexcept {
            static Program s_cInstance; ///< プログラムクラスインスタンス
            return s_cInstance;
        }

        //=====================================================================
        // インライン動的公開オーバーライド関数
        //---------------------------------------------------------------------
    public:
        //---------------------------------------------------------------------
        /// ノード名取得関数
        ///
        /// ノード名取得関数です。
        ///
        /// @param     なし
        /// @return    文字列
        /// @attention なし
        //---------------------------------------------------------------------
        inline virtual std::string const getName() const noexcept override {return "Program";}
    };
}
